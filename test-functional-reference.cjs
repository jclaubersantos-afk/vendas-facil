const fs=require('fs');
const html=fs.readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)];
const assert=(c,m)=>{if(!c)throw new Error(m)};
assert(scripts.length===3,`Expected original 3 scripts; found ${scripts.length}`);
scripts.forEach((s,i)=>{if(s[1].trim())new Function(s[1]);});
const app=scripts[1][1];
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert(new Set(ids).size===ids.length,'Duplicate HTML IDs');
const tabs=[...html.matchAll(/<button\b[^>]*class="tab(?:\s+active)?"[^>]*data-tab="([^"]+)"[^>]*>/g)].map(x=>x[1]);
assert(tabs.length>=5,`Expected navigation buttons, found ${tabs.length}`);
for(const id of tabs)assert(new RegExp(`<[^>]+id="${id}"[^>]+class="panel(?:\s+active)?"`).test(html),`Missing panel for tab ${id}`);
assert(/document\.querySelectorAll\('\.tab'\)\.forEach\(button=>button\.addEventListener\('click',\(\)=>changeTab\(button\.dataset\.tab\)\)\)/.test(app),'Tab click listeners are not attached');
assert(/function changeTab\(id\)\{document\.querySelectorAll\('\.tab'\)/.test(app),'Tab state transition function is missing');
for(const fn of ['saveProduct','saveSale','importBackup','saveReportPdf','saveDailyClosingPdf'])assert(new RegExp(`(?:async\\s+)?function\\s+${fn}\\s*\\(`).test(app),`Missing ${fn}`);
for(const id of ['saveProduct','saveSale','importBackup','exportBackup','exportReportPdf','gestaoPairButton'])assert(ids.includes(id),`Missing expected control ${id}`);
for(const token of ['gestao_claim_pairing_code','gestao_sync_sale','__gestaoSyncOutbox','__gestaoSyncAcknowledgements'])assert(html.includes(token),`Missing Gestión integration marker ${token}`);
assert(!html.includes('function restoreRouteOrderContext'),'Do not carry over late candidate route patch');
console.log(`Functional reference checks passed: ${tabs.length} linked tabs, ${ids.length} unique IDs, main action and Gestión markers.`);
